-- =============================================================================
-- Tópico : Sequences e colunas IDENTITY
-- Seção  : 07-ddl-e-objetos
-- Versão : 19c
-- Requer : usuário com CREATE SEQUENCE e CREATE TABLE
-- =============================================================================

-- 1. Sequence básica; CURRVAL só depois de NEXTVAL na sessão.
CREATE SEQUENCE tmp_seq START WITH 100 INCREMENT BY 10 NOCACHE;

-- Esperado: ORA-08002 (sequência TMP_SEQ.CURRVAL ainda não definida nesta sessão)
SELECT tmp_seq.CURRVAL FROM dual;

-- Esperado: 100 | 100
SELECT tmp_seq.NEXTVAL AS proximo FROM dual;
SELECT tmp_seq.CURRVAL AS atual   FROM dual;

-- NEXTVAL e CURRVAL na mesma linha: o NEXTVAL é gerado uma vez por linha,
-- e o CURRVAL da mesma linha devolve esse valor.
-- Esperado: 110 | 110
SELECT tmp_seq.NEXTVAL AS proximo, tmp_seq.CURRVAL AS atual FROM dual;

-- 2. Lacuna por ROLLBACK: o número não volta.
CREATE TABLE tmp_docs (id NUMBER, descricao VARCHAR2(20));

INSERT INTO tmp_docs VALUES (tmp_seq.NEXTVAL, 'confirmado');
COMMIT;
INSERT INTO tmp_docs VALUES (tmp_seq.NEXTVAL, 'desfeito');
ROLLBACK;
INSERT INTO tmp_docs VALUES (tmp_seq.NEXTVAL, 'confirmado');
COMMIT;

-- Esperado: 120 e 140 (o 130 foi perdido no rollback)
SELECT * FROM tmp_docs ORDER BY id;

-- 3. Onde NEXTVAL não é permitido.
-- Esperado: ORA-02287 (número de sequência não permitido aqui)
SELECT DISTINCT tmp_seq.NEXTVAL FROM dual;

-- Esperado: ORA-02287
SELECT tmp_seq.NEXTVAL FROM dual ORDER BY 1;

-- 4. Sequence como DEFAULT de coluna [12c+].
CREATE TABLE tmp_com_default (
    id         NUMBER DEFAULT tmp_seq.NEXTVAL PRIMARY KEY,
    descricao  VARCHAR2(20)
);
INSERT INTO tmp_com_default (descricao) VALUES ('a');
INSERT INTO tmp_com_default (descricao) VALUES ('b');

-- Esperado: 150 e 160
SELECT * FROM tmp_com_default ORDER BY id;

-- 5. Reposicionar a sequence [18c+].
ALTER SEQUENCE tmp_seq RESTART START WITH 1000;

-- Esperado: 1000
SELECT tmp_seq.NEXTVAL FROM dual;

-- 6. IDENTITY ALWAYS: não aceita valor informado.
CREATE TABLE tmp_ident_always (
    id         NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 CACHE 10) PRIMARY KEY,
    descricao  VARCHAR2(20)
);

INSERT INTO tmp_ident_always (descricao) VALUES ('gerado');

-- Esperado: ORA-32795 (não é possível inserir em uma coluna de identidade gerada sempre)
INSERT INTO tmp_ident_always (id, descricao) VALUES (99, 'informado');

-- 7. IDENTITY BY DEFAULT ON NULL: gera também quando o valor é NULL.
CREATE TABLE tmp_ident_on_null (
    id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    descricao  VARCHAR2(20)
);
INSERT INTO tmp_ident_on_null (id, descricao) VALUES (NULL, 'nulo vira gerado');
INSERT INTO tmp_ident_on_null (id, descricao) VALUES (500, 'informado');

-- Esperado: 1 e 500
SELECT * FROM tmp_ident_on_null ORDER BY id;

-- 8. A sequence interna da IDENTITY no dicionário.
-- Esperado: uma linha por tabela, com SEQUENCE_NAME = ISEQ$$_nnnnn
SELECT table_name, column_name, generation_type, sequence_name
  FROM user_tab_identity_cols
 WHERE table_name LIKE 'TMP_IDENT%'
 ORDER BY table_name;

-- Limpeza
DROP TABLE tmp_ident_on_null PURGE;
DROP TABLE tmp_ident_always PURGE;
DROP TABLE tmp_com_default PURGE;
DROP TABLE tmp_docs PURGE;
DROP SEQUENCE tmp_seq;
