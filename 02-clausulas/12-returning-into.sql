SET SERVEROUTPUT ON

-- Tabela com chave IDENTITY para mostrar a captura da chave gerada.
CREATE TABLE tmp_pedidos (
    id_pedido    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente   NUMBER NOT NULL,
    data_pedido  DATE   DEFAULT SYSDATE NOT NULL
);

-- 1. SQL*Plus/SQLcl: chave gerada para uma variável de ligação.
VARIABLE v_id NUMBER

INSERT INTO tmp_pedidos (id_cliente) VALUES (1)
RETURNING id_pedido INTO :v_id;

-- Esperado: 1
PRINT v_id

-- 2. Valor final de um UPDATE calculado.
VARIABLE v_preco NUMBER

UPDATE produtos
   SET preco_unitario = ROUND(preco_unitario * 1.05, 2)
 WHERE id_produto = 1
RETURNING preco_unitario INTO :v_preco;

-- Esperado: 41.9 (39.90 + 5%)
PRINT v_preco

ROLLBACK;

-- 3. PL/SQL: várias colunas de uma linha.
DECLARE
    v_id    tmp_pedidos.id_pedido%TYPE;
    v_data  tmp_pedidos.data_pedido%TYPE;
BEGIN
    INSERT INTO tmp_pedidos (id_cliente) VALUES (2)
    RETURNING id_pedido, data_pedido INTO v_id, v_data;

    DBMS_OUTPUT.PUT_LINE('Pedido ' || v_id || ' criado em ' || TO_CHAR(v_data, 'DD/MM/YYYY HH24:MI'));
    ROLLBACK;
END;
/

-- 4. PL/SQL: várias linhas com BULK COLLECT.
--    Reajuste de 10% na categoria Cadeiras (7): produtos 13 e 14.
DECLARE
    TYPE t_ids    IS TABLE OF produtos.id_produto%TYPE;
    TYPE t_precos IS TABLE OF produtos.preco_unitario%TYPE;
    v_ids    t_ids;
    v_precos t_precos;
BEGIN
    UPDATE produtos
       SET preco_unitario = ROUND(preco_unitario * 1.10, 2)
     WHERE id_categoria = 7
    RETURNING id_produto, preco_unitario BULK COLLECT INTO v_ids, v_precos;

    -- Esperado: 13 -> 867.9 e 14 -> 317.9
    FOR i IN 1 .. v_ids.COUNT LOOP
        DBMS_OUTPUT.PUT_LINE('Produto ' || v_ids(i) || ': novo preco ' || v_precos(i));
    END LOOP;

    ROLLBACK;
END;
/

