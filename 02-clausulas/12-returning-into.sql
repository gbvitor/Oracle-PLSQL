-- 6. DELETE com RETURNING: registrar o que foi apagado.
DECLARE
    v_qtd_total NUMBER := 0;
    TYPE t_num IS TABLE OF NUMBER;
    v_produtos  t_num;
    v_qtds      t_num;
BEGIN
    DELETE FROM itens_pedido
     WHERE id_pedido = 1024
    RETURNING id_produto, quantidade BULK COLLECT INTO v_produtos, v_qtds;

    -- Esperado: 2 itens apagados (produtos 8 e 9, 100 unidades no total)
    FOR i IN 1 .. v_produtos.COUNT LOOP
        v_qtd_total := v_qtd_total + v_qtds(i);
    END LOOP;
    DBMS_OUTPUT.PUT_LINE(v_produtos.COUNT || ' itens apagados, ' || v_qtd_total || ' unidades');

    ROLLBACK;
END;
/

