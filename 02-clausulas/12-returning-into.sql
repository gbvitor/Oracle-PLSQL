-- Versão : 19c
-- Requer : schema de exemplo (00-ambiente); usuário com CREATE TABLE
-- Os exemplos 1 e 2 usam comandos do SQL*Plus/SQLcl (VARIABLE, PRINT).
-- Tudo termina em ROLLBACK ou DROP.
