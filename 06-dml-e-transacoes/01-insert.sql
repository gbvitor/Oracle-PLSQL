-- 5. IDENTITY BY DEFAULT aceita valor informado e pode colidir com a sequência.
--    Tabela nova para os números serem previsíveis (um INSERT que falha
--    também consome um valor da sequência).
CREATE TABLE tmp_ident (
    id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR2(30)
);

INSERT INTO tmp_ident (id, nome) VALUES (1, 'id informado');

-- O primeiro valor gerado é 1, que já existe.
-- Esperado: ORA-00001 (restrição exclusiva violada)
INSERT INTO tmp_ident (nome) VALUES ('colide com o 1');

-- Ajustar a sequência da IDENTITY para depois do maior valor da coluna.
ALTER TABLE tmp_ident MODIFY id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE);

INSERT INTO tmp_ident (nome) VALUES ('depois do ajuste');

-- Esperado: 2
SELECT id FROM tmp_ident WHERE nome = 'depois do ajuste';

DROP TABLE tmp_ident PURGE;

-- 6. Sem lista de colunas: depende da ordem da tabela.
CREATE TABLE tmp_ordem (a VARCHAR2(10), b VARCHAR2(10));
INSERT INTO tmp_ordem VALUES ('valor_a', 'valor_b');

-- A tabela é recriada com as colunas em outra ordem...
DROP TABLE tmp_ordem PURGE;
CREATE TABLE tmp_ordem (b VARCHAR2(10), a VARCHAR2(10));

-- ...e o mesmo INSERT grava os valores trocados, sem erro.
INSERT INTO tmp_ordem VALUES ('valor_a', 'valor_b');

-- Esperado: a = valor_b | b = valor_a
SELECT a, b FROM tmp_ordem;

-- 7. Carga direta com APPEND: a sessão não lê a tabela antes do commit.
CREATE TABLE tmp_carga AS SELECT * FROM itens_pedido WHERE 1 = 0;

INSERT /*+ APPEND */ INTO tmp_carga SELECT * FROM itens_pedido;

-- Esperado: ORA-12838 (não é possível ler/modificar um objeto depois de modificá-lo em paralelo)
SELECT COUNT(*) FROM tmp_carga;

COMMIT;

-- Esperado: 54
SELECT COUNT(*) FROM tmp_carga;

-- Limpeza
DROP TABLE tmp_contatos PURGE;
DROP TABLE tmp_ordem PURGE;
DROP TABLE tmp_carga PURGE;
