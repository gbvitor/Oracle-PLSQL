CREATE TABLE tmp_contatos (
    id_contato   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR2(100) NOT NULL,
    origem       VARCHAR2(20)  DEFAULT 'manual' NOT NULL,
    canal        VARCHAR2(20)  DEFAULT ON NULL 'email',
    criado_em    DATE          DEFAULT SYSDATE NOT NULL
);

-- 1. Com lista de colunas; as omitidas recebem o DEFAULT.
INSERT INTO tmp_contatos (nome) VALUES ('Contato A');

-- Esperado: id 1 | manual | email | data de hoje
SELECT * FROM tmp_contatos;

-- 2. DEFAULT explícito e DEFAULT ON NULL.
--    "canal" recebe 'email' mesmo com NULL informado; "origem" não aceita NULL.
INSERT INTO tmp_contatos (nome, origem, canal) VALUES ('Contato B', DEFAULT, NULL);

-- Esperado: ORA-01400 (não é possível inserir NULL em ORIGEM)
INSERT INTO tmp_contatos (nome, origem) VALUES ('Contato C', NULL);

-- Esperado: Contato B | manual | email
SELECT nome, origem, canal FROM tmp_contatos WHERE nome = 'Contato B';

-- 3. INSERT ... SELECT: clientes pessoa jurídica com e-mail.
-- Esperado: 5 linhas inseridas (1, 2, 6, 8, 10)
INSERT INTO tmp_contatos (nome, origem, canal)
SELECT nome, 'clientes', 'email'
  FROM clientes
 WHERE tipo_pessoa = 'J'
   AND email IS NOT NULL;

-- 4. Várias linhas literais no 19c: SELECT ... FROM dual UNION ALL.
INSERT INTO tmp_contatos (nome, origem)
SELECT 'Contato D', 'lista' FROM dual UNION ALL
SELECT 'Contato E', 'lista' FROM dual UNION ALL
SELECT 'Contato F', 'lista' FROM dual;

-- Esperado: 10 linhas no total
SELECT COUNT(*) FROM tmp_contatos;

